"""Turn the results of one scenario run into a Markdown report (Prompt 9).

This file only formats. Scores, gap classes and comparisons arrive already
computed by ranking, gaps and compare; findings and references come from the
corpus that evidence.load() returns. Every line we write either carries a
citation like [ACRONYM, p. 4] or one of the labels HYPOTHETICAL, DERIVED,
INTERPRETATION or PROPOSAL, and check() finds the lines that do not.

to_html() is a small converter so the report can be opened in a browser and
printed to PDF. DOCX is out of scope.
"""

import html
import re

FOOTER = "Generated by PYRA. Not a safety certification."

SCENARIO_FIELDS = [
    ("o2_percent", "Oxygen", "%"),
    ("pressure", "Pressure", "kPa"),
    ("flow_speed", "Flow speed", "cm/s"),
    ("gravity", "Gravity", "g"),
    ("temperature", "Temperature", "K"),
    ("material", "Material", ""),
    ("fuel_phase", "Fuel phase", ""),
    ("pillar", "Pillar", ""),
    ("scale", "Scale", ""),
]
UNITS = {key: unit for key, _, unit in SCENARIO_FIELDS}
SCORE_NAMES = ["atmosphere", "flow", "gravity", "material", "objective", "scale", "measurement"]

# One fixed sentence per gap class. Axes that are DIRECTLY_TESTED get no proposal.
EXPERIMENTS = {
    "BOUNDED": "PROPOSAL: test {axis} at {value}, between the tested {low} and {high}, "
               "so the scenario is measured instead of bounded.",
    "ONE_SIDED": "PROPOSAL: test {axis} at {value}; the nearest tested value is {nearest}, "
                 "so today this is extrapolation.",
    "INSUFFICIENT": "PROPOSAL: repeat tests near {axis} = {value}; only {runs} run(s) fall "
                    "within tolerance.",
    "NOT_COMPARABLE": "PROPOSAL: test {axis} at {value} with hardware, scale and measurement "
                      "definitions that match the existing runs.",
    "NO_INDEXED_DATA": "PROPOSAL: a first test of {axis} at {value}; no indexed data covers this axis.",
}

CITATION = re.compile(r"\[[^\[\]]+, [^\[\]]+\]")
LABEL = re.compile(r"\b(HYPOTHETICAL|DERIVED|INTERPRETATION|PROPOSAL)\b")
SEPARATOR = re.compile(r"^\|[\s|:-]+\|$")


def _show(value, unit=""):
    if value is None or value == "":
        return "not provided"
    if isinstance(value, float):
        value = f"{value:.4g}"
    return f"{value} {unit}".strip()


def _scenario(scen):
    lines = ["## 1. Scenario", ""]
    for key, name, unit in SCENARIO_FIELDS:
        lines.append(f"- {name}: {_show(scen.get(key), unit)} (HYPOTHETICAL)")
    outputs = ", ".join(scen.get("outputs") or []) or "not provided"
    lines.append(f"- Outputs of interest: {outputs} (HYPOTHETICAL)")
    return lines


def _ranked(ranked):
    lines = ["## 2. Ranked investigations", ""]
    if not ranked:
        return lines + ["No investigations were ranked for this scenario (DERIVED)."]
    lines.append("| Rank | Investigation | Total | " + " | ".join(SCORE_NAMES)
                 + " | Evidence class | Label |")
    lines.append("|" + "---|" * (len(SCORE_NAMES) + 5))
    for rank, row in enumerate(ranked, 1):
        scores = [_show(row["scores"].get(name)) for name in SCORE_NAMES]
        lines.append(f"| {rank} | {row['acronym']} ({row['name']}) | {_show(row['total'])} | "
                     + " | ".join(scores)
                     + f" | {_show(row.get('evidence_class'))} | DERIVED |")
    lines.append("")
    for row in ranked:
        if row.get("explanation"):
            lines.append(f"- {row['acronym']}: {row['explanation']} (DERIVED)")
        if row.get("unmatched"):
            lines.append(f"- {row['acronym']} unmatched: {', '.join(row['unmatched'])} (DERIVED)")
    return lines


def _findings(ranked, corpus):
    lines = ["## 3. Key measured findings", ""]
    wanted = [row["investigation_id"] for row in ranked]
    by_id = {inv["id"]: inv for inv in (corpus or {}).get("investigations", [])}
    for inv_id in wanted:
        inv = by_id.get(inv_id)
        if inv is None:
            continue
        for finding in inv["findings"]:
            if finding["type"] == "MEASURED":
                page = finding["page_or_table"] or "page not provided"
                lines.append(f"- {finding['text']} [{inv['acronym']}, {page}]")
    if len(lines) == 2:
        lines.append("No MEASURED findings were found for the ranked investigations (DERIVED).")
    return lines


def _listed(value):
    if value is None:
        return []
    return [value] if isinstance(value, str) else list(value)


def _comparison(comparison):
    lines = ["## 4. Comparison highlights and comparability warnings", ""]
    if not comparison:
        return lines + ["No comparison was requested for this report (DERIVED)."]
    lines.append("| Field | Values | Same | Label |")
    lines.append("|---|---|---|---|")
    for row in comparison["rows"]:
        values = row["values"]
        if isinstance(values, dict):
            shown = "; ".join(f"{name}: {_show(v)}" for name, v in values.items())
        else:
            shown = "; ".join(_show(v) for v in values)
        lines.append(f"| {row['field']} | {shown} | {'yes' if row['same'] else 'no'} | DERIVED |")
    lines.append("")
    verdict = comparison["verdict"]
    word = "comparable" if verdict["comparable"] else "not directly comparable"
    lines.append(f"The investigations are {word} (DERIVED).")
    for reason in _listed(verdict.get("reasons")):
        lines.append(f"- Warning: {reason} (DERIVED)")
    for sentence in _listed(comparison.get("can_conclude")):
        lines.append(f"- Can conclude: {sentence} (DERIVED)")
    for sentence in _listed(comparison.get("cannot_conclude")):
        lines.append(f"- Cannot conclude: {sentence} (DERIVED)")
    return lines


def _gaps(gap_result):
    lines = ["## 5. Evidence coverage and gaps", ""]
    lines.append("| Axis | Class | Distance | Nearest value | Tested min | Tested max | Runs within | Label |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for axis, gap in gap_result["axes"].items():
        unit = UNITS.get(axis, "")
        lines.append(f"| {axis} | {gap['class']} | {_show(gap.get('distance'))} | "
                     f"{_show(gap.get('nearest_value'), unit)} | {_show(gap.get('tested_min'), unit)} | "
                     f"{_show(gap.get('tested_max'), unit)} | {_show(gap.get('runs_within'))} | DERIVED |")
    lines.append("")
    combination = gap_result["combination"]
    lines.append(f"Combination of all axes: {combination['class']}, "
                 f"{_show(combination.get('runs_matching'))} run(s) match every axis at once (DERIVED).")
    for run in gap_result.get("nearest_runs", []):
        source = run.get("source") or {}
        title = source.get("title") if isinstance(source, dict) else source
        lines.append(f"- Nearest run {run['run_id']}, distance {_show(run.get('distance'))} (DERIVED) "
                     f"[{run['acronym']}, {title or 'source not provided'}]")
    return lines


def _limitations(gap_result, ranked, corpus):
    lines = ["## 6. Limitations", ""]
    for sentence in gap_result.get("report", []):
        lines.append(f"- {sentence} (DERIVED)")
    by_id = {inv["id"]: inv for inv in (corpus or {}).get("investigations", [])}
    for row in ranked:
        inv = by_id.get(row["investigation_id"])
        for note in (inv or {}).get("notes", {}).get("limitation", []):
            lines.append(f"- {note} [{inv['acronym']}, limitation note]")
    gravity = gap_result["axes"].get("gravity")
    if gravity and gravity["class"] != "DIRECTLY_TESTED":
        lines.append("- Microgravity and 1 g results only bound partial-gravity behaviour; "
                     "the scenario gravity is not directly measured (INTERPRETATION).")
    lines.append("- PYRA shows indexed evidence and where it stops; it does not predict fire "
                 "behaviour (INTERPRETATION).")
    return lines


def _experiments(scen, gap_result):
    lines = ["## 7. Suggested experiments", ""]
    for axis, gap in gap_result["axes"].items():
        template = EXPERIMENTS.get(gap["class"])
        if template is None:
            continue
        unit = UNITS.get(axis, "")
        lines.append("- " + template.format(
            axis=axis, value=_show(scen.get(axis), unit),
            low=_show(gap.get("tested_min"), unit), high=_show(gap.get("tested_max"), unit),
            nearest=_show(gap.get("nearest_value"), unit), runs=_show(gap.get("runs_within"))))
    if len(lines) == 2:
        lines.append("Every axis is DIRECTLY_TESTED, so no experiment is proposed (DERIVED).")
    return lines


def _references_from(ranked, corpus):
    by_id = {inv["id"]: inv for inv in (corpus or {}).get("investigations", [])}
    found = []
    for row in ranked:
        inv = by_id.get(row["investigation_id"])
        for pub in (inv or {}).get("publications", []):
            found.append(dict(pub, acronym=inv["acronym"], accessed=None))
    return found


def _references(references):
    lines = ["## 8. References", ""]
    for ref in references:
        lines.append(f"- [{ref['acronym']}, publication {ref['id']}] {ref['title']}. "
                     f"URL: {_show(ref.get('url'))}. NTRS: {_show(ref.get('ntrs_id'))}. "
                     f"Accessed: {_show(ref.get('accessed'))}.")
    if len(lines) == 2:
        lines.append("No references were passed to the report (DERIVED).")
    return lines


def build(scen, ranked, gap_result, comparison=None, references=None, corpus=None):
    """The full Markdown report. references defaults to the publications of the ranked investigations."""
    if references is None:
        references = _references_from(ranked, corpus)
    sections = [
        ["# PYRA scenario report", ""],
        _scenario(scen), _ranked(ranked), _findings(ranked, corpus), _comparison(comparison),
        _gaps(gap_result), _limitations(gap_result, ranked, corpus), _experiments(scen, gap_result),
        _references(references), ["---", FOOTER],
    ]
    return "\n\n".join("\n".join(section) for section in sections) + "\n"


def _is_table_header(lines, index):
    return (lines[index].startswith("|") and index + 1 < len(lines)
            and SEPARATOR.match(lines[index + 1].strip()) is not None)


def check(markdown):
    """Lines that have neither a citation nor a label. An empty list means the report passes."""
    lines = markdown.splitlines()
    bad = []
    for index, line in enumerate(lines):
        text = line.strip()
        if (not text or text.startswith("#") or text == "---" or text == FOOTER
                or SEPARATOR.match(text) or _is_table_header(lines, index)):
            continue
        if not CITATION.search(text) and not LABEL.search(text):
            bad.append(line)
    return bad


def _cells(line):
    return [html.escape(cell.strip()) for cell in line.strip().strip("|").split("|")]


def to_html(markdown):
    """A minimal HTML page (headings, tables, lists, paragraphs) for printing to PDF."""
    lines = markdown.splitlines()
    body = []
    index = 0
    while index < len(lines):
        text = lines[index].strip()
        if _is_table_header(lines, index):
            body.append("<table><tr>" + "".join(f"<th>{c}</th>" for c in _cells(text)) + "</tr>")
            index += 2
            while index < len(lines) and lines[index].startswith("|"):
                body.append("<tr>" + "".join(f"<td>{c}</td>" for c in _cells(lines[index])) + "</tr>")
                index += 1
            body.append("</table>")
            continue
        if text.startswith("- "):
            body.append("<ul>")
            while index < len(lines) and lines[index].startswith("- "):
                body.append(f"<li>{html.escape(lines[index][2:])}</li>")
                index += 1
            body.append("</ul>")
            continue
        heading = re.match(r"^(#{1,6}) (.*)", text)
        if heading:
            level = len(heading.group(1))
            body.append(f"<h{level}>{html.escape(heading.group(2))}</h{level}>")
        elif text == "---":
            body.append("<hr>")
        elif text:
            body.append(f"<p>{html.escape(text)}</p>")
        index += 1
    style = ("body{font-family:sans-serif;max-width:60em;margin:2em auto}"
             "table{border-collapse:collapse}td,th{border:1px solid #999;padding:2px 6px}")
    return ("<!doctype html><html><head><meta charset=\"utf-8\"><title>PYRA report</title>"
            f"<style>{style}</style></head><body>\n" + "\n".join(body) + "\n</body></html>\n")
