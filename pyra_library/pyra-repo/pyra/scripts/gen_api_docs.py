"""Generate docs/api.md from the public API of pyra.provenance (signatures and docstrings).

Run:  python scripts/gen_api_docs.py          (rewrites docs/api.md)
The test suite regenerates the text and fails if docs/api.md is out of date.
"""

from __future__ import annotations

import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pyra.provenance as prov  # noqa: E402
import pyra.physics.calorimetry as calorimetry  # noqa: E402
import pyra.io as io  # noqa: E402
import pyra.matching as matching  # noqa: E402
import pyra.compare as compare  # noqa: E402
import pyra.adapters as adapters  # noqa: E402
import pyra.report as report  # noqa: E402
import pyra.service as service  # noqa: E402
import pyra.schema as schema  # noqa: E402
import pyra.units as units  # noqa: E402
import pyra.uq as uq  # noqa: E402

OUT = ROOT / "docs" / "api.md"


def _sig(obj: object, *, drop_return: bool = False) -> str:
    try:
        sig = inspect.signature(obj)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return "(...)"
    if drop_return:
        sig = sig.replace(return_annotation=inspect.Signature.empty)
    # <Status.DERIVED: 1> -> Status.DERIVED
    text = re.sub(r"<(\w+)\.(\w+): \d+>", r"\1.\2", str(sig))
    # drop the quotes that "from __future__ import annotations" leaves around annotations
    return re.sub(r"(: |-> )'([^']*)'", r"\1\2", text)


def _doc(obj: object) -> str:
    """Own docstring only (no inherited text, no dataclass boilerplate)."""
    raw = obj.__dict__.get("__doc__") if inspect.isclass(obj) else inspect.getdoc(obj)
    text = inspect.cleandoc(raw or "").strip()
    if inspect.isclass(obj) and text.startswith(f"{obj.__name__}("):
        return ""
    return text


def _first_paragraph(text: str) -> str:
    return text.split("\n\n")[0].replace("\n", " ").strip()


def render() -> str:
    lines = [
        "# API reference: `pyra.provenance`",
        "",
        "<!-- Generated by scripts/gen_api_docs.py. Do not edit by hand. -->",
        "",
        "All names below can be imported from `pyra.provenance`; "
        "the most common ones also from `pyra`.",
        "",
    ]
    for name in sorted(prov.__all__):
        obj = getattr(prov, name)
        if inspect.isclass(obj):
            lines += [f"## class `{name}{_sig(obj, drop_return=True)}`", ""]
            doc = _doc(obj)
            if doc:
                lines += [doc, ""]
            for mname, member in inspect.getmembers(obj):
                if mname.startswith("_") or not callable(member):
                    continue
                if not (inspect.isfunction(member) or inspect.ismethod(member)):
                    continue
                if mname in getattr(obj, "__dataclass_fields__", {}):
                    continue
                lines += [f"* `{name}.{mname}{_sig(member)}`"]
                first = _first_paragraph(_doc(member))
                if first:
                    lines += [f"  {first}"]
            lines.append("")
        elif callable(obj):
            lines += [f"## `{name}{_sig(obj)}`", ""]
            doc = _doc(obj)
            if doc:
                lines += [doc, ""]
    for module, title in (
        (units, "pyra.units"),
        (schema, "pyra.schema"),
        (io, "pyra.io"),
        (matching, "pyra.matching"),
        (compare, "pyra.compare"),
        (adapters, "pyra.adapters"),
        (report, "pyra.report"),
        (service, "pyra.service"),
        (calorimetry, "pyra.physics.calorimetry"),
        (uq, "pyra.uq"),
    ):
        lines += [f"## Module `{title}`", ""]
        for name in sorted(module.__all__):
            obj = getattr(module, name)
            if inspect.isclass(obj):
                lines += [f"* class `{name}`"]
            elif callable(obj):
                lines += [f"* `{name}{_sig(obj)}`"]
            else:
                lines += [f"* `{name}`"]
            first = _first_paragraph(_doc(obj))
            if first:
                lines += [f"  {first}"]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT}")
